//! Font isolation (DESIGN §4.12): the AppImage's bundled WebKit/Skia
//! crashes on the host's COLRv1 emoji fonts (FreeType ABI mismatch). At
//! startup we generate a fontconfig file that includes the host config,
//! adds the bundled CBDT `NotoColorEmoji.ttf` dir, and rejects fonts with
//! `color=true` AND `outline=true`; `FONTCONFIG_FILE` points at it.

use std::ffi::OsStr;
use std::path::{Path, PathBuf};

/// The bundled CBDT emoji font file name.
pub const EMOJI_FONT_FILE: &str = "NotoColorEmoji.ttf";

/// The host fontconfig main file the generated config includes.
pub const SYSTEM_FONTS_CONF: &str = "/etc/fonts/fonts.conf";

/// Prefix of the generated config file name: `<prefix><pid>.conf`.
pub const GENERATED_CONF_PREFIX: &str = "peakbot-desktop-fonts-";

/// `<root>/usr/bin/<exe>` → `<root>/usr/share/peakbot-desktop/fonts`
/// (the exe's grandparent joined `share/peakbot-desktop/fonts`; no `..`).
/// `None` when the exe has no grandparent (e.g. `/peakbot-desktop`).
pub fn bundled_font_dir(exe: &Path) -> Option<PathBuf> {
    let root = exe.parent()?.parent()?;
    Some(root.join("share").join("peakbot-desktop").join("fonts"))
}

/// The golden fonts.conf XML with `font_dir` XML-escaped
/// (`&` → `&amp;`, `<` → `&lt;`, `>` → `&gt;`). Pure.
pub fn render_fonts_conf(font_dir: &str) -> String {
    const T: &str = r#"<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by peakbot-desktop (DESIGN §4.12). Host config + bundled CBDT emoji;
     color outline fonts (COLRv0/COLRv1/SVG) hidden: the bundled WebKit/Skia
     crashes on COLRv1 with the host's FreeType. -->
<fontconfig>
  <include ignore_missing="yes">/etc/fonts/fonts.conf</include>
  <dir>/usr/share/fonts</dir>
  <dir prefix="xdg">fonts</dir>
  <cachedir prefix="xdg">fontconfig</cachedir>
  <dir>{FONT_DIR}</dir>
  <selectfont>
    <rejectfont>
      <pattern>
        <patelt name="color"><bool>true</bool></patelt>
        <patelt name="outline"><bool>true</bool></patelt>
      </pattern>
    </rejectfont>
  </selectfont>
  <alias binding="same">
    <family>emoji</family>
    <prefer><family>Noto Color Emoji</family></prefer>
  </alias>
</fontconfig>
"#;
    T.replace("{FONT_DIR}", &xml_escape(font_dir))
}

/// Escape the three XML metacharacters (`&` first, then `<` and `>`).
fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// `Some(xml)` iff `existing` is `None` (no user `FONTCONFIG_FILE`),
/// `bundled_font_dir` is `Some`, and the dir is valid UTF-8.
pub fn emoji_fonts_conf(
    existing: Option<&OsStr>,
    bundled_font_dir: Option<&Path>,
) -> Option<String> {
    if existing.is_some() {
        return None;
    }
    let dir = bundled_font_dir?.to_str()?;
    Some(render_fonts_conf(dir))
}

/// `xdg_runtime_dir` when `Some`, non-empty, and absolute; else
/// `std::env::temp_dir()`.
pub fn fonts_conf_dir(xdg_runtime_dir: Option<&OsStr>) -> PathBuf {
    match xdg_runtime_dir {
        Some(p) if !p.is_empty() && Path::new(p).is_absolute() => PathBuf::from(p),
        _ => std::env::temp_dir(),
    }
}

/// Write `<dir>/<GENERATED_CONF_PREFIX><pid>.conf`: `remove_file` (a
/// `NotFound` is ok — a stale file from a previous run) then
/// `OpenOptions` write + `create_new`. Returns the path.
pub fn write_fonts_conf(dir: &Path, pid: u32, xml: &str) -> std::io::Result<PathBuf> {
    use std::io::Write;
    let path = dir.join(format!("{GENERATED_CONF_PREFIX}{pid}.conf"));
    match std::fs::remove_file(&path) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(e),
    }
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)?;
    f.write_all(xml.as_bytes())?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg(unix)]
    use std::os::unix::ffi::OsStrExt;

    /// The golden XML (DESIGN §4.12); `{FONT_DIR}` is the placeholder.
    /// Note the trailing newline after `</fontconfig>`.
    fn golden(font_dir: &str) -> String {
        const T: &str = r#"<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by peakbot-desktop (DESIGN §4.12). Host config + bundled CBDT emoji;
     color outline fonts (COLRv0/COLRv1/SVG) hidden: the bundled WebKit/Skia
     crashes on COLRv1 with the host's FreeType. -->
<fontconfig>
  <include ignore_missing="yes">/etc/fonts/fonts.conf</include>
  <dir>/usr/share/fonts</dir>
  <dir prefix="xdg">fonts</dir>
  <cachedir prefix="xdg">fontconfig</cachedir>
  <dir>{FONT_DIR}</dir>
  <selectfont>
    <rejectfont>
      <pattern>
        <patelt name="color"><bool>true</bool></patelt>
        <patelt name="outline"><bool>true</bool></patelt>
      </pattern>
    </rejectfont>
  </selectfont>
  <alias binding="same">
    <family>emoji</family>
    <prefer><family>Noto Color Emoji</family></prefer>
  </alias>
</fontconfig>
"#;
        T.replace("{FONT_DIR}", font_dir)
    }

    // t122.
    #[test]
    fn t122_bundled_font_dir_resolves_appimage_root() {
        let got = bundled_font_dir(Path::new("/tmp/.mount_x/usr/bin/peakbot-desktop"));
        assert_eq!(
            got,
            Some(PathBuf::from(
                "/tmp/.mount_x/usr/share/peakbot-desktop/fonts"
            )),
            "got {got:?}"
        );
    }

    // t123.
    #[test]
    fn t123_bundled_font_dir_without_grandparent_is_none() {
        let got = bundled_font_dir(Path::new("/peakbot-desktop"));
        assert_eq!(got, None, "no grandparent ⇒ None; got {got:?}");
    }

    // t124.
    #[test]
    fn t124_render_fonts_conf_matches_golden() {
        assert_eq!(
            render_fonts_conf("/a/fonts"),
            golden("/a/fonts"),
            "the rendered config must be the golden XML, byte for byte"
        );
    }

    // t125.
    #[test]
    fn t125_render_fonts_conf_xml_escapes_the_font_dir() {
        let out = render_fonts_conf("/x/a&b<c>");
        assert!(
            out.contains("<dir>/x/a&amp;b&lt;c&gt;</dir>"),
            "the font dir must be XML-escaped in the <dir> element; got:\n{out}"
        );
        assert!(
            !out.contains("&b"),
            "no raw & from the font dir may leak into the XML; got:\n{out}"
        );
    }

    // t126.
    #[test]
    fn t126_emoji_fonts_conf_none_when_user_config_exists() {
        let got = emoji_fonts_conf(Some(OsStr::new("/u.conf")), Some(Path::new("/u/fonts")));
        assert_eq!(got, None, "a user FONTCONFIG_FILE must win; got {got:?}");
    }

    // t127.
    #[test]
    fn t127_emoji_fonts_conf_none_without_bundled_dir() {
        assert_eq!(emoji_fonts_conf(None, None), None);
    }

    // t128.
    #[test]
    fn t128_emoji_fonts_conf_renders_golden_when_no_user_config() {
        let got = emoji_fonts_conf(None, Some(Path::new("/u/fonts")));
        assert_eq!(got, Some(render_fonts_conf("/u/fonts")), "got {got:?}");
    }

    // t129.
    #[cfg(unix)]
    #[test]
    fn t129_emoji_fonts_conf_none_for_non_utf8_dir() {
        let dir = Path::new(OsStr::from_bytes(b"/\xff"));
        let got = emoji_fonts_conf(None, Some(dir));
        assert_eq!(got, None, "a non-UTF-8 dir cannot be rendered; got {got:?}");
    }

    // t130.
    #[test]
    fn t130_fonts_conf_dir_prefers_xdg_runtime_dir() {
        assert_eq!(
            fonts_conf_dir(Some(OsStr::new("/run/user/1000"))),
            PathBuf::from("/run/user/1000")
        );
        assert_eq!(fonts_conf_dir(None), std::env::temp_dir());
        assert_eq!(
            fonts_conf_dir(Some(OsStr::new(""))),
            std::env::temp_dir(),
            "an empty dir is unusable"
        );
        assert_eq!(
            fonts_conf_dir(Some(OsStr::new("rel"))),
            std::env::temp_dir(),
            "a relative dir is unusable"
        );
    }

    // t131.
    #[test]
    fn t131_write_fonts_conf_writes_pid_named_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = write_fonts_conf(dir.path(), 42, "x").expect("write");
        assert_eq!(
            path,
            dir.path().join("peakbot-desktop-fonts-42.conf"),
            "got {path:?}"
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "x");
    }

    // t132.
    #[test]
    fn t132_write_fonts_conf_replaces_stale_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("peakbot-desktop-fonts-42.conf");
        std::fs::write(&path, "stale content from a previous run").unwrap();
        let got = write_fonts_conf(dir.path(), 42, "x").expect("write");
        assert_eq!(got, path);
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "x",
            "the stale file must be replaced, not appended to or kept"
        );
    }
}
