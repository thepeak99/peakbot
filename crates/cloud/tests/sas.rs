//! RED tests: SAS six-word enrollment check (spec §5) — 66-bit
//! MSB-first extraction, BIP-39 mapping, head-frozen pure-API property.
mod common;

use cloud::Head;
use cloud::sas;
use common::*;
use sha2::{Digest, Sha256};

/// The SAS input card bytes for the independent vector: an arbitrary CE
/// card byte string (SAS never parses the card, spec §5.1).
fn vector_card() -> Vec<u8> {
    (0..1234u32).map(|i| ((i * 7 + 3) % 256) as u8).collect()
}

fn vector_head() -> Head {
    Head {
        seq: 7,
        hash: [0x42; 32],
    }
}

// -- embedded BIP-39 list ------------------------------------------------------

#[test]
fn bip39_list_sha256_matches_spec() {
    // spec §5.3: SHA-256 over the embedded list joined with `\n` plus a
    // final `\n`.
    let list = sas::bip39_english();
    assert_eq!(list.len(), 2048);
    let joined = list.join("\n") + "\n";
    let digest = Sha256::digest(joined.as_bytes());
    assert_eq!(
        hex(&digest),
        "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
    );
}

// -- independent vector (computed in python3 from the spec formula) ------------
//
// INDEPENDENT: computed with python3 (hashlib.sha3_256) from spec
// §5.1–§5.3 — NOT generated by the crate:
//   d = sha3_256(u32(8) ‖ "pbc1 sas" ‖ u32(len) ‖ card ‖ u64(7) ‖ 0x42*32)
//   card = bytes((7*i+3) % 256 for i in range(1234))
//   d = 142927b359410a20554f2e84e4a7d3596eb720e719b99fc8e3fcd036660ba2c1
//   x = first 66 bits (MSB-first) = 0x50a49ecd65042881
//   w = [161, 585, 1894, 1428, 133, 129]
//   words = before empty under raw awful awake

#[test]
fn digest_matches_independent_python_vector() {
    let d = sas::digest(&vector_card(), &vector_head());
    assert_eq!(
        hex32(d),
        "142927b359410a20554f2e84e4a7d3596eb720e719b99fc8e3fcd036660ba2c1"
    );
}

#[test]
fn words_match_independent_python_vector() {
    let w = sas::words(&vector_card(), &vector_head());
    assert_eq!(w.as_indices(), [161, 585, 1894, 1428, 133, 129]);
    assert_eq!(
        w.words(),
        ["before", "empty", "under", "raw", "awful", "awake"]
    );
}

// -- 66-bit MSB-first extraction (spec §5.2) -------------------------------------

#[test]
fn bit_extraction_all_zero_digest_is_all_index_zero() {
    // spec §15 `sas_edge`: all-zero digest → indices 0 (word "abandon").
    assert_eq!(sas::words_from_digest(&[0x00; 32]).as_indices(), [0; 6]);
}

#[test]
fn bit_extraction_all_ff_digest_is_all_index_2047() {
    // spec §15 `sas_edge`: all-0xFF digest → 66 bits set → indices 2047
    // (word "zoo").
    assert_eq!(sas::words_from_digest(&[0xFF; 32]).as_indices(), [2047; 6]);
}

// -- head/card sensitivity ---------------------------------------------------------

#[test]
fn changing_head_changes_words() {
    let card = vector_card();
    let h1 = vector_head();
    let h2 = Head {
        seq: 8,
        hash: [0x42; 32],
    };
    assert_ne!(sas::words(&card, &h1), sas::words(&card, &h2));
}

#[test]
fn changing_card_changes_words() {
    let h = vector_head();
    let c1 = vector_card();
    let mut c2 = c1.clone();
    c2[0] ^= 1;
    assert_ne!(sas::words(&c1, &h), sas::words(&c2, &h));
}

// -- §5.5 pure-API property: the head is frozen into the value --------------------

#[test]
fn head_frozen_before_card_revealed_pure_api() {
    // §5.5 R1/R2 as a pure-API property: `SasWords` freezes the (card,
    // head) pair at construction. There is no API that re-derives a
    // SasWords with a new head, so a value cannot silently track a later
    // chain change. The observable consequence: the same input gives the
    // same value (stable), and a later head gives a different value.
    let card = vector_card();
    let h1 = vector_head();
    let h2 = Head {
        seq: h1.seq + 1,
        hash: [0x43; 32],
    };
    let w1 = sas::words(&card, &h1);
    assert_eq!(w1, sas::words(&card, &h1)); // stable
    assert_ne!(w1, sas::words(&card, &h2)); // no hidden re-derivation
}

// -- display -------------------------------------------------------------------------

#[test]
fn display_is_two_rows_of_three_numbered_lowercase() {
    let w = sas::words(&vector_card(), &vector_head());
    let d = w.display();
    let rows: Vec<&str> = d.lines().collect();
    assert_eq!(rows.len(), 2);
    let words = w.words();
    for (r, (row, chunk)) in rows.iter().zip([&words[0..3], &words[3..6]]).enumerate() {
        let mut pos = 0usize;
        for (n, word) in chunk.iter().enumerate() {
            // spec §5.3: numbering runs 1..6 across both rows.
            let num = (3 * r + n + 1).to_string();
            assert!(
                row[pos..].starts_with(&format!("{num} ")),
                "row {row:?} missing number {n}"
            );
            pos += num.len() + 1;
            assert!(row[pos..].starts_with(word), "row {row:?} missing {word}");
            pos += word.len();
            // Skip the separator (spec shows two spaces; be lenient here).
            while pos < row.len() && row.as_bytes()[pos] == b' ' {
                pos += 1;
            }
        }
    }
}
